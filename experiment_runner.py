# Temp file names written to project root for Mojo to load
_TMP_FILES = {
    "X_train": "_exp_X_train.csv",
    "X_test":  "_exp_X_test.csv",
    "y_train": "_exp_y_train.csv",
    "y_test":  "_exp_y_test.csv",
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def compute_split_sizes(n_rows: int, train_split: float) -> tuple[int, int]:
    """Mirror Mojo's split.mojo: n_train = floor(n_rows * train_split)."""
    n_train = int(math.floor(n_rows * train_split))
    n_test  = n_rows - n_train
    return n_train, n_test


def load_csv_fast(path: str, nrows: int | None = None) -> np.ndarray:
    """
    Load a headerless CSV, optionally capped at nrows rows.
    Uses pandas nrows= for efficient early-stopping on large files.
    """
    try:
        import pandas as pd
        return pd.read_csv(path, header=None, nrows=nrows).values.astype(np.float32)
    except ImportError:
        return np.loadtxt(path, delimiter=",", dtype=np.float32,
                          max_rows=nrows)


def prepare_data_split(ds: dict, n_train: int, n_test: int,
                       project_root: str) -> tuple[np.ndarray, ...]:
    """
    Load dataset, shuffle + split with a fixed seed, write four temp CSVs
    to project_root so Mojo can load the exact same rows.

    Returns (X_train, X_test, y_train, y_test) as numpy arrays.
    The split is deterministic (random_state=42) so every run of the same
    config produces the same train/test partition, making results reproducible
    and directly comparable between sklearn and Mojo.
    """
    nrows = ds["n_rows"]
    X = load_csv_fast(os.path.join(project_root, ds["features_path"]), nrows=nrows)
    y = load_csv_fast(os.path.join(project_root, ds["labels_path"]),   nrows=nrows).ravel()

    X_train, X_test, y_train, y_test = sk_split(
        X, y, train_size=n_train, test_size=n_test,
        shuffle=True, random_state=42,
    )

    # Write with enough precision for Float32 round-trip (%.8g ≈ 8 sig figs)
    np.savetxt(os.path.join(project_root, _TMP_FILES["X_train"]),
               X_train, delimiter=",", fmt="%.8g")
    np.savetxt(os.path.join(project_root, _TMP_FILES["X_test"]),
               X_test,  delimiter=",", fmt="%.8g")
    # Labels are integers stored as floats — write without decimals
    np.savetxt(os.path.join(project_root, _TMP_FILES["y_train"]),
               y_train.reshape(-1, 1), delimiter=",", fmt="%.0f")
    np.savetxt(os.path.join(project_root, _TMP_FILES["y_test"]),
               y_test.reshape(-1, 1),  delimiter=",", fmt="%.0f")

    return X_train, X_test, y_train, y_test


def cleanup_temp_files(project_root: str) -> None:
    for name in _TMP_FILES.values():
        p = os.path.join(project_root, name)
        if os.path.exists(p):
            os.remove(p)


# ---------------------------------------------------------------------------
# sklearn baseline  (uses the same pre-split arrays as Mojo)
# ---------------------------------------------------------------------------

def run_sklearn_baseline(ds: dict,
                         X_train: np.ndarray, X_test: np.ndarray,
                         y_train: np.ndarray, y_test: np.ndarray) -> list[dict]:
    """Time sklearn brute-force and KD-tree KNN on the pre-split arrays."""
    results = []
    k = ds["k"]

    for algo, label in [("brute", "sklearn_brute"), ("kd_tree", "sklearn_kdtree")]:
        print(f"    Running {label} — {ds['num_runs']} runs...")
        clf = KNeighborsClassifier(n_neighbors=k, algorithm=algo,
                                   metric="euclidean", leaf_size=30)
        clf.fit(X_train, y_train)
        for run in range(ds["num_runs"]):
            t0     = time.perf_counter()
            y_pred = clf.predict(X_test)
            elapsed = time.perf_counter() - t0
            acc = float((y_pred == y_test).mean() * 100.0)
            results.append({"algorithm": label, "run": run + 1,
                            "time_seconds": elapsed, "accuracy_pct": acc})

    return results


# ---------------------------------------------------------------------------
# Mojo code-generation + execution
# ---------------------------------------------------------------------------

def generate_mojo_source(ds: dict, n_train: int, n_test: int) -> str:
    return MOJO_TEMPLATE.format(
        dataset_name = ds["name"],
        n_train      = n_train,
        n_test       = n_test,
        n_features   = ds["n_features"],
        k            = ds["k"],
        num_runs     = ds["num_runs"],
    )


def parse_mojo_output(stdout: str) -> list[dict]:
    results = []
    for line in stdout.splitlines():
        if not line.startswith("RESULT,"):
            continue
        parts = line.split(",")
        if len(parts) != 5:
            continue
        _, algorithm, run_str, time_str, acc_str = parts
        try:
            results.append({
                "algorithm":    algorithm,
                "run":          int(run_str),
                "time_seconds": float(time_str),
                "accuracy_pct": None if acc_str.strip() == "N/A" else float(acc_str),
            })
        except ValueError:
            pass
    return results


def run_mojo_experiment(ds: dict, n_train: int, n_test: int,
                        mojo_bin: str, project_root: str) -> list[dict]:
    """Generate and JIT-run the Mojo experiment; return parsed results."""
    tmp_mojo = os.path.join(project_root, "_exp_tmp.mojo")

    source = generate_mojo_source(ds, n_train, n_test)
    with open(tmp_mojo, "w") as f:
        f.write(source)

    print(f"    Running Mojo (JIT) — {ds['num_runs']} runs...")
    try:
        result = subprocess.run(
            [mojo_bin, "run", "_exp_tmp.mojo"],
            cwd=project_root,
            capture_output=True,
            text=True,
            timeout=7200,
        )
    finally:
        if os.path.exists(tmp_mojo):
            os.remove(tmp_mojo)

    if result.returncode != 0:
        print(f"    ERROR: Mojo experiment exited with code {result.returncode}")
        stderr_preview = result.stderr.strip()[:800]
        if stderr_preview:
            print(f"    stderr:\n{stderr_preview}")
        return []

    return parse_mojo_output(result.stdout)


