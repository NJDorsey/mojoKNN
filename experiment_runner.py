#!/usr/bin/env python3
"""
mojoKNN Experiment Runner
=========================
Orchestrates benchmarks across multiple datasets by:
  1. Splitting data once in Python (shuffled, random_state=42) and writing
     temp CSVs so both sklearn and Mojo see the exact same training/test rows.
  2. Running a sklearn KNeighborsClassifier baseline on those split arrays.
  3. Generating a Mojo source file with compile-time dataset constants,
     compiling it with `mojo build` (optimized), running the binary, then
     parsing results from stdout.

Output: a timestamped CSV in results/ with one row per (dataset, algorithm, run).

Usage:
    python experiment_runner.py                        # uses experiment_config.toml
    python experiment_runner.py my_config.toml

CSV columns:
    batch_timestamp, machine, dataset, n_rows, n_train, n_test,
    n_features, k, algorithm, run, time_seconds, accuracy_pct
"""

