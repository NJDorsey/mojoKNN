# Main
# ---------------------------------------------------------------------------

CSV_FIELDS = [
    "batch_timestamp", "machine",
    "dataset", "group", "n_rows", "n_train", "n_test", "n_features", "k",
    "algorithm", "run", "time_seconds", "accuracy_pct",
]


def main():
    config_path = sys.argv[1] if len(sys.argv) > 1 else "experiment_config.toml"

    if not os.path.exists(config_path):
        print(f"Config file not found: {config_path}")
        sys.exit(1)

    with open(config_path, "rb") as f:
        config = tomllib.load(f)

    runner_cfg  = config.get("runner", {})
    output_dir  = runner_cfg.get("output_dir", "results")
    mojo_bin    = runner_cfg.get("mojo_bin", "mojo")
    datasets    = config.get("datasets", [])

    if not datasets:
        print("No datasets defined in config.")
        sys.exit(1)

    os.makedirs(output_dir, exist_ok=True)

    timestamp    = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    machine      = socket.gethostname()
    project_root = str(Path(config_path).parent.resolve())
    output_csv   = os.path.join(output_dir, f"batch_{timestamp}.csv")

    print("=" * 60)
    print("mojoKNN Experiment Runner")
    print(f"  Config:   {config_path}")
    print(f"  Batch:    {timestamp}")
    print(f"  Machine:  {machine}")
    print(f"  Output:   {output_csv}")
    print(f"  Datasets: {len(datasets)}")
    print("=" * 60)

    with open(output_csv, "w", newline="") as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=CSV_FIELDS)
        writer.writeheader()

        for ds in datasets:
            n_train, n_test = compute_split_sizes(ds["n_rows"], ds["train_split"])
            meta = {
                "batch_timestamp": timestamp,
                "machine":    machine,
                "dataset":    ds["name"],
                "group":      ds.get("group", ""),
                "n_rows":     ds["n_rows"],
                "n_train":    n_train,
                "n_test":     n_test,
                "n_features": ds["n_features"],
                "k":          ds["k"],
            }

            print(f"\n[{ds['name']}]  {ds['n_rows']} rows  "
                  f"{ds['n_features']} features  K={ds['k']}  "
                  f"{ds['num_runs']} runs  "
                  f"(train={n_train} / test={n_test})")

            # ---- Split data once; write temp CSVs for Mojo ----
            try:
                print(f"    Preparing data split (random_state=42)...")
                X_train, X_test, y_train, y_test = prepare_data_split(
                    ds, n_train, n_test, project_root
                )
            except Exception as e:
                print(f"    Data preparation failed: {e}")
                continue

            try:
                # ---- sklearn baseline ----
                sk_results = run_sklearn_baseline(
                    ds, X_train, X_test, y_train, y_test
                )
                for r in sk_results:
                    writer.writerow({**meta, **r})
                csvfile.flush()
                sk_times = [r["time_seconds"] for r in sk_results]
                sk_mean_acc = np.mean([r["accuracy_pct"] for r in sk_results])
                print(f"    sklearn_brute  mean: {np.mean(sk_times):.4f}s  "
                      f"acc={sk_mean_acc:.1f}%")

                # ---- Mojo experiment ----
                mojo_results = run_mojo_experiment(
                    ds, n_train, n_test, mojo_bin, project_root
                )
                for r in mojo_results:
                    writer.writerow({**meta, **r})
                csvfile.flush()

                for algo in ["brute_simd", "kdtree_simd", "kdtree_build",
                            "sklearn_kdtree"]:
                    runs = [r for r in sk_results + mojo_results
                            if r["algorithm"] == algo]
                    if not runs:
                        continue
                    times = [r["time_seconds"] for r in runs]
                    accs  = [r["accuracy_pct"] for r in runs
                             if r["accuracy_pct"] is not None]
                    acc_str = f"  acc={np.mean(accs):.1f}%" if accs else ""
                    print(f"    {algo:<14} mean: {np.mean(times):.4f}s{acc_str}")

                # Speedup vs sklearn (exclude first run to avoid warmup skew)
                sk_steady = sk_times[1:] if len(sk_times) > 1 else sk_times
                bf_times  = [r["time_seconds"] for r in mojo_results
                             if r["algorithm"] == "brute_simd"]
                kd_times  = [r["time_seconds"] for r in mojo_results
                             if r["algorithm"] == "kdtree_simd"]
                bf_steady = bf_times[1:] if len(bf_times) > 1 else bf_times
                kd_steady = kd_times[1:] if len(kd_times) > 1 else kd_times

                if sk_steady and bf_steady:
                    print(f"    brute_simd speedup vs sklearn:   "
                          f"{np.mean(sk_steady)/np.mean(bf_steady):.1f}x")
                if sk_steady and kd_steady:
                    print(f"    kdtree_simd speedup vs sklearn:  "
                          f"{np.mean(sk_steady)/np.mean(kd_steady):.1f}x")

            except Exception as e:
                print(f"    Experiment failed: {e}")
                import traceback; traceback.print_exc()
            finally:
                cleanup_temp_files(project_root)

    print(f"\n{'=' * 60}")
    print(f"Done. Results saved to: {output_csv}")


if __name__ == "__main__":
    main()
